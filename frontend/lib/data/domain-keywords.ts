export type KeywordCategory = "computer_science"

export const keywordCatalog: Record<KeywordCategory, string[]> = {
  computer_science: computerScienceKeywords,
}

export function searchKeywords(
  query: string,
  category: KeywordCategory = "computer_science",
  limit = 12,
) {
  const normalized = query.trim().toLowerCase()
  const pool = keywordCatalog[category]
  if (!normalized) {
    return pool.slice(0, limit)
  }

  const directMatches = pool.filter((keyword) => keyword.toLowerCase() === normalized)
  const partialMatches = pool.filter(
    (keyword) => keyword.toLowerCase().includes(normalized) && !directMatches.includes(keyword),
  )
  const suggestions = [...directMatches, ...partialMatches]
  return suggestions.slice(0, limit)
}
